/*
# EXPRESSIONS
An expression is a combination of one or more values, operators,
and postgres function that evaluate to a value.

SELECT column1, column2, columnN
FROM table_name
WHERE [CONDITION | EXPRESSION];

## BOOLEAN EXPRESSION
SELECT column1, column2, columnN
FROM table_name
WHERE SINGLE VALUE MATCHING EXPRESSION;

## NUMERIC EXPRESSION
SELECT numeric_expression AS OPERATION_NAME
[FROM table_name WHERE CONDITION];

## DATE EXPRESSIONS
Date Expressions return the current system date and time values
and these expressions are used in various data manipulations.
*/